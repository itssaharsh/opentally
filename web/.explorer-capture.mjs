// Real-time capture of this run's release and contract on Blockscout, for the video's explorer scene.
import { chromium } from "playwright";
import fs from "node:fs";
const [,, addr, hash, outDir] = process.argv;
const BS = "https://base-sepolia.blockscout.com";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1, recordVideo: { dir: outDir, size: { width: 1920, height: 1080 } } });
await ctx.addInitScript(() => { const f = () => { const s = document.createElement("style"); s.textContent = ".sevioads,[id^='sevio-ad'],div:has(> .sevioads){display:none!important}*{scrollbar-width:none!important}html{zoom:1.4}"; document.documentElement.appendChild(s); }; document.readyState === "loading" ? document.addEventListener("DOMContentLoaded", f) : f(); });
const p = await ctx.newPage();
const t0 = Date.now(); const marks = {};
await p.goto(`${BS}/tx/${hash}?tab=logs`, { waitUntil: "domcontentloaded", timeout: 90000 });
await p.getByText("Released(").first().waitFor({ timeout: 90000 });
await p.waitForTimeout(1500);
marks.tx = (Date.now() - t0) / 1000;
await p.waitForTimeout(6800);
await p.evaluate(() => window.scrollTo({ top: 300, behavior: "smooth" }));
await p.waitForTimeout(3800);
await p.goto(`${BS}/address/${addr}?tab=contract`, { waitUntil: "domcontentloaded", timeout: 90000 });
await p.getByText("Contract source code verified").first().waitFor({ timeout: 90000 });
await p.waitForTimeout(1500);
marks.contract = (Date.now() - t0) / 1000;
await p.waitForTimeout(9000);
const v = await p.video().path();
await ctx.close(); await b.close();
fs.writeFileSync(`${outDir}/marks.json`, JSON.stringify({ ...marks, video: v }));
console.log(JSON.stringify({ ...marks, video: v }));
