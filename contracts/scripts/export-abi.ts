import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const names = ["OpenTally", "OpenTallyFactory", "TestUSD"];
let ts = "// Generated by contracts/scripts/export-abi.ts. Do not edit.\n";
for (const n of names) {
  const art = JSON.parse(readFileSync(`artifacts/contracts/${n}.sol/${n}.json`, "utf8"));
  ts += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(art.abi)} as const;\n`;
}
mkdirSync("../web/src/lib", { recursive: true });
writeFileSync("../web/src/lib/abi.ts", ts);
console.log("abi written");
